'use strict';
// Writes nix/sharp-deps.nix: the npm tarballs of sharp (and what it needs on Linux) with the hashes already in
// package-lock.json, so the Nix build can unpack them without a separate npmDepsHash. Run it again after sharp's version changes:
//   node tools/nix-sharp.js

const fs = require('fs');
const path = require('path');

const lock = require('../package-lock.json').packages;

function entry(name) {
  const p = lock[`node_modules/${name}`];
  if (!p || !p.resolved || !p.integrity) throw new Error(`${name} is not in package-lock.json (npm install first)`);
  return `    { name = "${name}"; src = fetchurl { url = "${p.resolved}"; hash = "${p.integrity}"; }; }`;
}
const list = (names) => `[\n${names.map(entry).join('\n')}\n  ]`;

const arch = { 'x86_64-linux': 'x64', 'aarch64-linux': 'arm64' };
const out = `# Generated by tools/nix-sharp.js from package-lock.json. Do not edit.
{ fetchurl }: {
  common = ${list(['sharp', '@img/colour', 'detect-libc', 'semver'])};
${Object.entries(arch).map(([system, a]) => `  ${system} = ${list([`@img/sharp-linux-${a}`, `@img/sharp-libvips-linux-${a}`])};`).join('\n')}
}
`;
fs.mkdirSync(path.join(__dirname, '..', 'nix'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '..', 'nix', 'sharp-deps.nix'), out);
console.log('wrote nix/sharp-deps.nix');
